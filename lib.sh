#!/bin/bash
set -euo pipefail

console_user="$(stat -f '%Su' /dev/console 2>/dev/null || true)"
if [[ -n "${SUDO_USER:-}" && "${SUDO_USER}" != "root" ]]; then
  REAL_USER="${SUDO_USER}"
elif [[ -n "${console_user}" && "${console_user}" != "root" && "${console_user}" != "loginwindow" ]]; then
  REAL_USER="${console_user}"
else
  REAL_USER="${USER:-$(id -un)}"
fi
USER_HOME="$(dscl . -read "/Users/${REAL_USER}" NFSHomeDirectory 2>/dev/null | awk '{print $2}')"
USER_HOME="${USER_HOME:-$HOME}"
KS_DIR="${USER_HOME}/Library/Application Support/amnezia-manual-ks"
USER_PREFS="${USER_HOME}/Library/Preferences/org.amneziavpn.AmneziaVPN.plist"
PF_CONF_DIR="${KS_DIR}"

# shellcheck disable=SC1091
export HOME="${USER_HOME}"
source "${KS_DIR}/config.env"
# PF_CONF_DIR in config may expand with wrong HOME under sudo — force user path
PF_CONF_DIR="${KS_DIR}"

need_sudo() {
  if [[ "${EUID}" -ne 0 ]]; then
    exec sudo -E HOME="${USER_HOME}" SUDO_USER="${REAL_USER}" "$0" "$@"
  fi
}

fix_amnezia_prefs_ownership() {
  if [[ -f "${USER_PREFS}" ]]; then
    chown "${REAL_USER}:staff" "${USER_PREFS}" 2>/dev/null || chown "${REAL_USER}" "${USER_PREFS}" || true
    chmod 600 "${USER_PREFS}" || true
  fi
}

clear_amnezia_strict_flags() {
  fix_amnezia_prefs_ownership
  # Write as the real user so ownership never flips back to root
  if [[ -f "${USER_PREFS}" ]]; then
    sudo -u "${REAL_USER}" defaults write "${USER_PREFS}" Conf.strictKillSwitchEnabled -bool false 2>/dev/null || true
  fi
  defaults write /var/root/Library/Preferences/org.amneziavpn.AmneziaVPN.plist Conf.strictKillSwitchEnabled -bool false 2>/dev/null || true
}

write_block_rules() {
  local mode="$1"

  echo "# Generated by manual-ks $(date)"
  echo "block drop out all"
  echo ""
  echo "pass out quick on lo0 all"
  echo "pass in quick on lo0 all"
  echo ""
  echo "pass out quick proto udp from any port 68 to any port 67"
  echo "pass in quick proto udp from any port 67 to any port 68"
  echo ""

  if [[ -n "${AMNEZIA_SERVER_IP:-}" ]]; then
    echo "pass out quick inet to ${AMNEZIA_SERVER_IP}/32"
    echo "pass in quick inet from ${AMNEZIA_SERVER_IP}/32"
  fi
  echo ""

  for dns in "${DNS_ALLOW[@]}"; do
    echo "pass out quick proto udp to ${dns} port 53"
    echo "pass out quick proto tcp to ${dns} port 53"
  done
  echo ""

  for cidr in "${OFFICE_ALLOW_CIDRS[@]}"; do
    [[ -z "${cidr}" || "${cidr}" == \#* ]] && continue
    echo "pass out quick inet to ${cidr}"
    echo "pass in quick inet from ${cidr}"
  done
  echo ""

  for cidr in "${EXTRA_VPN_ALLOW_CIDRS[@]:-}"; do
    [[ -z "${cidr}" || "${cidr}" == \#* ]] && continue
    echo "pass out quick inet to ${cidr}"
    echo "pass in quick inet from ${cidr}"
  done
  echo ""

  if [[ "${mode}" == "connected" ]]; then
    ifconfig -l | tr ' ' '\n' | awk '/^utun[0-9]+$/ {
      print "pass out quick on " $1 " all"
      print "pass in quick on " $1 " all"
    }'
    echo ""
  fi
}

redshield_endpoint_ip() {
  local conf="${USER_HOME}/Library/Application Support/redshieldvpn/Red Shield VPN/redlink.conf"
  [[ -f "${conf}" ]] || return 0
  awk -F'[=:]' '/^Endpoint/{gsub(/ /,"",$2); print $2; exit}' "${conf}"
}

write_split_table() {
  local wan="$1"
  # Not /var/run: macOS empties it on every reboot, and the list of Russian
  # networks (taken from Amnezia routes once) would be lost.
  local file="/Library/Application Support/NetDot/netdot-split.txt"
  if [[ ! -f "${file}" && -f /var/run/netdot-split.txt ]]; then
    cp /var/run/netdot-split.txt "${file}"
  fi
  netstat -rn -f inet | awk -v wan="${wan}" '
    NR > 1 && $1 != "default" && $NF == wan && $1 ~ /\// && $1 !~ /^224\./ && $1 !~ /^255\./ { print $1 }
  ' | sort -u > "${file}.new"
  local new_count old_count
  new_count="$(wc -l < "${file}.new" | tr -d ' ')"
  old_count=0
  [[ -f "${file}" ]] && old_count="$(wc -l < "${file}" | tr -d ' ')"
  if [[ "${new_count}" -ge 20 || ! -f "${file}" ]]; then
    mv "${file}.new" "${file}"
  else
    rm -f "${file}.new"
  fi
  echo "${file}"
}

# Server hosts Happ is connected to (outbound "address" fields, not DNS URLs).
happ_server_hosts() {
  local p="${USER_HOME}/Library/Group Containers/group.su.ffg.happ/Library/Preferences/group.su.ffg.happ.plist"
  [[ -f "${p}" ]] || return 0
  plutil -extract connectedConfigJson raw -o - "${p}" 2>/dev/null \
    | grep -oE '"address"[[:space:]]*:[[:space:]]*"[^"]+"' \
    | sed -E 's/.*"([^"]+)"$/\1/' | grep -v '/' || true
}

# IPv4 addresses for a host name, asked from public DNS (allowed by the shield).
resolve_v4() {
  local host="$1"
  if [[ "${host}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "${host}"
    return 0
  fi
  # System resolver first (VPN DNS or the home router), public DNS as fallback.
  # 198.18.0.0/15 are placeholder answers from a VPN app, not real addresses.
  # Ask the Wi-Fi router first: it is on the local network, so the question
  # never enters a VPN tunnel. With Happ "connected" but its server blocked,
  # every lookup through the tunnel hung, a new server address was never
  # learned, and so never allowed: a dead loop.
  local found="" router
  router="$(ipconfig getoption "${NETDOT_WAN:-en0}" domain_name_server 2>/dev/null || true)"
  if [[ -n "${router}" ]]; then
    found="$(dig +short +time=2 +tries=1 A "${host}" "@${router}" 2>/dev/null | grep -E '^[0-9.]+$' || true)"
  fi
  if [[ -z "${found}" ]]; then
    found="$(dscacheutil -q host -a name "${host}" 2>/dev/null | awk '/^ip_address:/{print $2}')"
  fi
  if [[ -z "${found}" ]]; then
    found="$(dig +short +time=2 +tries=1 A "${host}" @1.1.1.1 2>/dev/null || true)"
  fi
  printf '%s\n' "${found}" \
    | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | grep -vE '^198\.(18|19)\.' | sort -u || true
}

# Look up many hosts at once, giving up after 8 seconds. With the internet
# down each lookup hangs, and one by one they made the shield take minutes.
resolve_all() {
  local dir host i=0 waited=0
  local -a pids=()
  dir="$(mktemp -d)"
  for host in "$@"; do
    [[ -z "${host}" || "${host}" == \#* ]] && continue
    resolve_v4 "${host}" > "${dir}/${i}" 2>/dev/null &
    pids+=("$!")
    i=$((i + 1))
  done
  while (( waited < 8 )) && jobs -r | grep -q .; do
    sleep 1
    waited=$((waited + 1))
  done
  kill ${pids[@]:-} 2>/dev/null || true
  cat "${dir}"/* 2>/dev/null || true
  rm -rf "${dir}"
}

# Merge IPs from stdin into a list file. The list only grows: a failed lookup
# must never drop an address the VPN still needs.
remember_ips() {
  local file="$1"
  { awk 1 "${file}" 2>/dev/null || true; cat; } \
    | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' \
    | grep -vE '^(10\.|127\.|172\.(1[6-9]|2[0-9]|3[01])\.|192\.168\.|198\.1[89]\.)' \
    | sort -u > "${file}.new" || true
  mv "${file}.new" "${file}"
  chown "${REAL_USER}:staff" "${file}" 2>/dev/null || true
}

# Home network of the physical interface, e.g. 192.168.1.0/24 (router, printer, DNS).
lan_cidr() {
  local iface="$1" ip mask
  ip="$(ipconfig getifaddr "${iface}" 2>/dev/null || true)"
  mask="$(ipconfig getoption "${iface}" subnet_mask 2>/dev/null || true)"
  [[ -n "${ip}" && -n "${mask}" ]] || return 0
  local i1 i2 i3 i4 m1 m2 m3 m4 bits=0 octet
  IFS=. read -r i1 i2 i3 i4 <<< "${ip}"
  IFS=. read -r m1 m2 m3 m4 <<< "${mask}"
  for octet in "${m1}" "${m2}" "${m3}" "${m4}"; do
    while (( octet & 128 )); do
      bits=$((bits + 1))
      octet=$(((octet << 1) & 255))
    done
  done
  echo "$((i1 & m1)).$((i2 & m2)).$((i3 & m3)).$((i4 & m4))/${bits}"
}

write_shield_rules() {
  local wan
  # Default route is the VPN tunnel while it is up. Block the physical
  # interface (en0), otherwise the real IP stays open.
  # No "exit" in awk: with a long route table (Red Shield adds hundreds)
  # netstat got a broken pipe, pipefail turned it into an error, and the
  # whole shield script died silently before writing any rule.
  wan="$(netstat -rn -f inet | awk '$1=="default" && $NF ~ /^en/ && !w {w=$NF} END {print w}')"
  if [[ -z "${wan}" || "${wan}" == utun* ]]; then
    wan="en0"
  fi
  local split_file
  split_file="$(write_split_table "${wan}")"
  local split_count
  split_count="$(wc -l < "${split_file}" | tr -d ' ')"
  local rs_ip
  rs_ip="$(redshield_endpoint_ip || true)"
  local lan
  lan="$(lan_cidr "${wan}")"

  # Look up VPN servers and direct sites now, not only when the shield was
  # first turned on: Red Shield moves servers to new addresses.
  local endpoints_file="${KS_DIR}/endpoints.txt"
  local direct_file="${KS_DIR}/direct-ips.txt"
  {
    resolve_all "${AMNEZIA_SERVER_HOST:-}" $(happ_server_hosts)
    [[ -n "${rs_ip}" ]] && echo "${rs_ip}"
    true
  } | remember_ips "${endpoints_file}"
  resolve_all "${DIRECT_DOMAINS[@]:-}" | remember_ips "${direct_file}"

  echo "# shield: foreign traffic may leave only via utun"
  echo "pass out quick on lo0 all"
  echo "pass in quick on lo0 all"
  ifconfig -l | tr ' ' '\n' | awk '/^utun[0-9]+$/ {
    print "pass out quick on " $1 " all"
    print "pass in quick on " $1 " all"
  }'
  echo "pass out quick on ${wan} proto udp from any port 68 to any port 67"
  echo "pass in quick on ${wan} proto udp from any port 67 to any port 68"
  if [[ -n "${AMNEZIA_SERVER_IP:-}" ]]; then
    echo "pass out quick on ${wan} inet to ${AMNEZIA_SERVER_IP}/32"
  fi
  if [[ -n "${rs_ip}" ]]; then
    echo "pass out quick on ${wan} inet to ${rs_ip}/32"
  fi
  for cidr in "${EXTRA_VPN_ALLOW_CIDRS[@]:-}"; do
    [[ -z "${cidr}" || "${cidr}" == \#* ]] && continue
    echo "pass out quick on ${wan} inet to ${cidr}"
  done
  local ip
  while read -r ip; do
    [[ -n "${ip}" ]] && echo "pass out quick on ${wan} inet to ${ip}/32"
  # awk 1 ends every file with a newline: NetDot writes endpoints.txt without
  # one, and plain cat glued two addresses into one line pf could not read.
  done < <(awk 1 "${endpoints_file}" "${direct_file}" 2>/dev/null \
    | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | sort -u)
  if [[ -n "${lan}" ]]; then
    echo "pass out quick on ${wan} inet to ${lan}"
  fi
  for cidr in "${OFFICE_ALLOW_CIDRS[@]}"; do
    [[ -z "${cidr}" || "${cidr}" == \#* ]] && continue
    echo "pass out quick on ${wan} inet to ${cidr}"
  done
  for dns in "${DNS_ALLOW[@]}"; do
    echo "pass out quick on ${wan} proto udp to ${dns} port 53"
    echo "pass out quick on ${wan} proto tcp to ${dns} port 53"
  done
  # Happ asks Google DNS over HTTPS directly for the sites it sends past the
  # VPN (.ru and friends). Blocked, those names did not resolve under Happ.
  echo "pass out quick on ${wan} proto tcp to 8.8.8.8/32 port 443"
  echo "pass out quick on ${wan} proto tcp to 8.8.4.4/32 port 443"
  if [[ "${split_count}" -gt 0 ]]; then
    echo "table <netdot_split> persist file \"${split_file}\""
    echo "pass out quick on ${wan} inet to <netdot_split>"
  fi
  echo "block drop out quick on ${wan} all"
}

write_pf_conf() {
  local mode="$1"
  local block_conf="${PF_CONF_DIR}/manual-ks.block.conf"
  local full_conf="${PF_CONF_DIR}/manual-ks.full.conf"

  mkdir -p "${PF_CONF_DIR}"
  if [[ "${mode}" == "shield" ]]; then
    write_shield_rules > "${block_conf}"
  else
    write_block_rules "${mode}" > "${block_conf}"
  fi
  chown "${REAL_USER}:staff" "${block_conf}" 2>/dev/null || true

  {
    cat /etc/pf.conf
    echo ""
    echo "# ----- amnezia-manual-ks (GEN BY SCRIPT) -----"
    echo "anchor \"${PF_ANCHOR}\""
    echo "load anchor \"${PF_ANCHOR}\" from \"${block_conf}\""
    echo "# ----- End amnezia-manual-ks -----"
  } > "${full_conf}"
  chown "${REAL_USER}:staff" "${full_conf}" 2>/dev/null || true

  echo "${full_conf}"
}

load_pf() {
  local conf="$1"
  pfctl -f "${conf}" >/dev/null
  pfctl -e >/dev/null 2>&1 || true
}

# Rebuild the shield only when the rules came out different (new server
# address, other Wi-Fi, new tunnel). Does nothing unless the shield is on.
refresh_shield() {
  local mark
  mark="$(tr -d '[:space:]' < "${KS_DIR}/internet-state" 2>/dev/null || true)"
  if [[ "${mark}" != "shield" ]]; then
    echo "not shielded"
    return 0
  fi
  local block_conf="${PF_CONF_DIR}/manual-ks.block.conf"
  local fresh
  fresh="$(mktemp)"
  write_shield_rules > "${fresh}"
  if cmp -s "${fresh}" "${block_conf}"; then
    rm -f "${fresh}"
    echo "unchanged"
    return 0
  fi
  rm -f "${fresh}"
  load_pf "$(write_pf_conf shield)"
  echo "updated"
}

flush_manual_ks() {
  pfctl -a "${PF_ANCHOR}" -F all >/dev/null 2>&1 || true
  pfctl -f /etc/pf.conf >/dev/null 2>&1 || true
}

disable_all_pf() {
  # Drop Amnezia's leftover enable token if present, then disable pf.
  local token_file="/Library/Application Support/AmneziaVPN/pf/pf.token"
  if [[ -f "${token_file}" ]]; then
    local token
    token="$(tr -d '[:space:]' < "${token_file}" || true)"
    if [[ -n "${token}" ]]; then
      pfctl -X "${token}" >/dev/null 2>&1 || true
    fi
    rm -f "${token_file}" || true
  fi
  pfctl -d >/dev/null 2>&1 || true
}

stop_amnezia_tunnel() {
  pkill -f '/Applications/AmneziaVPN.app/Contents/MacOS/tun2socks' 2>/dev/null || true
  pkill -f '/Applications/AmneziaVPN.app/Contents/MacOS/xray' 2>/dev/null || true
}

restart_amnezia_service() {
  launchctl kickstart -k system/AmneziaVPN-service 2>/dev/null || true
}

write_internet_state() {
  local mode="$1"
  mkdir -p "${KS_DIR}"
  printf '%s\n' "${mode}" > "${KS_DIR}/internet-state"
  chown "${REAL_USER}:staff" "${KS_DIR}/internet-state" 2>/dev/null || true
}

resolve_server_ip() {
  local ip
  ip="$(dscacheutil -q host -a name "${AMNEZIA_SERVER_HOST}" 2>/dev/null | awk '/ip_address:/ && !ip {ip=$2} END {print ip}')"
  if [[ -n "${ip}" ]]; then
    AMNEZIA_SERVER_IP="${ip}"
  fi
}
